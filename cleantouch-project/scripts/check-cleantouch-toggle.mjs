import { chromium } from '../.local/browser-check/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5180/', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: '화면 스캔 켜기' }).click();
  await page.getByRole('button', { name: '취소', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '화면 스캔 켜기' }).getAttribute('aria-pressed'), 'false');
  await page.screenshot({ path: 'artifacts/cleantouch-toggle-home.png', fullPage: true });
  await page.getByRole('button', { name: '화면 스캔 켜기' }).click();
  await page.getByRole('button', { name: '체험 시작', exact: true }).click();
  await page.getByRole('button', { name: '다른 앱을 보는 상황 체험 →' }).click();
  await page.locator('video').waitFor();
  assert.equal(await page.locator('.floating-scan').count(), 0);
  assert.equal(await page.locator('.device button').count(), 0);
  await page.waitForTimeout(11000);
  assert.equal(await page.locator('video').evaluate(video => video.paused), false);
  await page.getByRole('button', { name: '← CleanTouch 앱으로 돌아가기' }).click();
  assert.equal(await page.getByRole('button', { name: '스캔 종료하고 자동 분석' }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: '스캔 종료하고 자동 분석' }).click();
  await page.getByRole('status').waitFor();
  await page.getByText('인식한 상품 3개', { exact: false }).waitFor();
  assert.equal(await page.locator('.product-card').count(), 3);
  await page.getByRole('button', { name: '신발', exact: true }).click();
  assert.equal(await page.locator('.product-card').count(), 1);
  await page.getByRole('button', { name: '전체', exact: true }).click();
  await page.getByRole('textbox', { name: '상품 이름으로 찾기' }).fill('재킷');
  assert.equal(await page.locator('.product-card').count(), 1);
  await page.getByRole('textbox', { name: '상품 이름으로 찾기' }).fill('');
  await page.screenshot({ path: 'artifacts/cleantouch-toggle-results.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: 'artifacts/cleantouch-toggle-mobile.png', fullPage: true });
  await page.getByRole('button', { name: '새 화면 스캔 시작', exact: true }).click();
  await page.getByRole('button', { name: '체험 시작', exact: true }).click();
  assert.equal(await page.locator('.product-card').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS: consent cancellation, >10s ON, unobstructed video playback, OFF -> automatic results, all 3 products, filter/search, repeat session, mobile overflow, JS errors.');
} finally { await browser.close(); }
