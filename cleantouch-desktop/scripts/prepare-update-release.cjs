const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const yaml = require('js-yaml');
const { version } = require('../package.json');
const dist = path.resolve(__dirname, '..', process.env.CLEANTOUCH_BUILD_DIR || 'dist');
const metadata = yaml.load(fs.readFileSync(path.join(dist, 'latest.yml'), 'utf8'));
if (metadata.version !== version || metadata.files?.length !== 1) throw new Error('Unexpected update metadata');
const entry = metadata.files[0];
const filename = decodeURIComponent(entry.url);
if (path.basename(filename) !== filename || !filename.endsWith('.exe')) throw new Error('Invalid release filename');
const source = path.join(dist, `CleanTouch Setup ${version}.exe`);
const bytes = fs.readFileSync(source);
if (crypto.createHash('sha512').update(bytes).digest('base64') !== entry.sha512) throw new Error('Installer checksum mismatch');
const destination = path.join(dist, 'update-release');
fs.mkdirSync(destination, { recursive: true });
fs.copyFileSync(source, path.join(destination, filename));
fs.copyFileSync(`${source}.blockmap`, path.join(destination, `${filename}.blockmap`));
fs.copyFileSync(path.join(dist, 'latest.yml'), path.join(destination, 'latest.yml'));
fs.copyFileSync(path.join(dist, `CleanTouch ${version}.exe`), path.join(destination, `CleanTouch-Portable-${version}.exe`));
console.log(`Update release ${version}: installer filename and SHA-512 verified. Files: ${destination}`);
